#!/usr/bin/env python3
"""Rasterize a crisp, monochrome 7x12 DS font at its native display size."""

import argparse
import hashlib
import struct
import unicodedata
from pathlib import Path

if __package__:
    from .pack_theme_font import glyph_bitmap, pack_font
else:
    from pack_theme_font import glyph_bitmap, pack_font

from PIL import ImageFont

PROJECT_ROOT = Path(__file__).resolve().parents[1]
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
GLYPH_HEIGHT = 12
BASELINE = 9


def extended_header(source: Path) -> str:
    """Share bounded fallback glyphs without enlarging every loaded theme font."""
    codepoints = list(range(0x100, 0x180)) + list(range(0x370, 0x500))
    fonts = {size: ImageFont.truetype(str(source), size) for size in (10, 9)}
    missing = {size: (font.getmask(chr(0x10FFFF), mode="1").size,
                      bytes(font.getmask(chr(0x10FFFF), mode="1")))
               for size, font in fonts.items()}
    glyphs, supported = [], []
    for codepoint in codepoints:
        character = chr(codepoint)
        bitmap = None
        if unicodedata.category(character)[0] not in {"C", "M"}:
            for size, font in fonts.items():
                mask = font.getmask(character, mode="1")
                if (mask.size, bytes(mask)) == missing[size]:
                    continue
                for baseline in (10, 9, 8):
                    try:
                        bitmap = glyph_bitmap(font, character, baseline)
                        break
                    except ValueError:
                        pass
                if bitmap is not None:
                    break
        supported.append(int(bitmap is not None))
        glyphs.append([sum((3 if bitmap and bitmap.getpixel((x, y)) else 0) << (x * 2)
                           for x in range(7)) for y in range(12)])
    lines = ["/* Generated by tools/make_font.py --extended-only.",
             f" * DejaVu Sans Mono: {hashlib.sha256(source.read_bytes()).hexdigest()}",
             " * Latin Extended-A, Greek and Cyrillic; see THIRD_PARTY.md. */",
             "static const unsigned char ui_font_extended_supported[528] = {",
             "    " + ", ".join(map(str, supported)), "};",
             "static const uint16_t ui_font_extended[528][12] = {"]
    for codepoint, rows in zip(codepoints, glyphs):
        lines.append("    {" + ", ".join(f"0x{row:04x}" for row in rows)
                     + f"}}, /* U+{codepoint:04X} */")
    return "\n".join(lines + ["};", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--extended-only", action="store_true", help="Regenerate the shared Unicode fallback table")
    args = parser.parse_args()
    if args.extended_only:
        output = PROJECT_ROOT / "arm9/source/ui/font_extended.h"
        output.write_text(extended_header(Path(FONT_PATH)))
        print("Wrote Latin Extended-A, Greek and Cyrillic fallback glyphs to " + str(output))
        return
    packed = pack_font(Path(FONT_PATH), 11, BASELINE)
    rows = struct.unpack("<1140H", packed[16:])
    glyphs = [rows[index : index + GLYPH_HEIGHT] for index in range(0, len(rows), GLYPH_HEIGHT)]

    output = PROJECT_ROOT / "arm9/source/ui/font.h"
    output.write_text(
        "/* Generated by tools/make_font.py. DejaVu Sans Mono; see THIRD_PARTY.md. */\n"
        "#define UI_FONT_ADVANCE 7\n#define UI_FONT_HEIGHT 12\n"
        "static const unsigned short ui_font[95][UI_FONT_HEIGHT] = {\n"
        + "".join("    {" + ",".join(map(str, rows)) + "},\n" for rows in glyphs)
        + "};\n"
    )


if __name__ == "__main__":
    main()
